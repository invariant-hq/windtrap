let stream_matches_frozen_literals () =
  List.iter
    (fun (seed, label, outputs) ->
      let rec check_outputs index state = function
        | [] -> ()
        | expected :: remaining ->
            let word, state = Seed.bits64 state in
            expect_hex
              ~label:(Printf.sprintf "%s output %d" label index)
              expected word;
            check_outputs (index + 1) state remaining
      in
      check_outputs 1 (Seed.make seed) outputs)
    stream_vectors

let stream_matches_published_splitmix64_vector () =
  let state = Seed.make 1234567L in
  let first, state = Seed.bits64 state in
  let second, state = Seed.bits64 state in
  let third, _ = Seed.bits64 state in
  equal ~msg:"published output 1" hex64 6457827717110365317L first;
  equal ~msg:"published output 2" hex64 3203168211198807973L second;
  (* 9817491932198370423 mod 2^64, as a signed int64 *)
  equal ~msg:"published output 3" hex64 (-8629252141511181193L) third

let states_are_immutable_and_deterministic () =
  let initial = Seed.make 0L in
  let first, successor = Seed.bits64 initial in
  let repeated, repeated_successor = Seed.bits64 initial in
  equal ~msg:"reused initial output" hex64 first repeated;
  let second, _ = Seed.bits64 successor in
  let repeated_second, _ = Seed.bits64 repeated_successor in
  equal ~msg:"reused successor output" hex64 second repeated_second;
  expect_hex ~label:"first word" "e220a8397b1dcdaf" first;
  expect_hex ~label:"second word" "6e789e6aa1b965f4" second

let full_width_output_preserves_the_sign_bit () =
  let state = Seed.make 0L in
  let first, state = Seed.bits64 state in
  let _, state = Seed.bits64 state in
  let third, _ = Seed.bits64 state in
  is_true ~msg:"high-bit output is preserved as a full int64 pattern"
    (Int64.compare first 0L < 0);
  is_true ~msg:"low-half output keeps its sign bit clear"
    (Int64.compare third 0L >= 0)

(* Bounded draws *)

let bounded_edge_vectors () =
  let vectors =
    [
      (0x0000000000000001L, "0000000000000000");
      (0x0000000000000002L, "0000000000000001");
      (0x0000000000000003L, "0000000000000001");
      (0x000000000000000aL, "0000000000000005");
      (0x0000000000000100L, "00000000000000af");
      (0x7fffffffffffffffL, "6220a8397b1dcdb0");
      (0x4000000000000001L, "2220a8397b1dcdac");
    ]
  in
  List.iter
    (fun (bound, expected) ->
      let value, successor = Seed.below ~bound (Seed.make 0L) in
      expect_hex ~label:("bounded " ^ hex_of_int64 bound) expected value;
      checkf
        (Int64.compare value 0L >= 0 && Int64.compare value bound < 0)
        "bounded result %s is outside [0,%s)" (hex_of_int64 value)
        (hex_of_int64 bound);
      let next, _ = Seed.bits64 successor in
      expect_hex ~label:"one-word successor" "6e789e6aa1b965f4" next)
    vectors

let bounded_single_rejection_consumes_both_words () =
  let bound = 0x4000000000000001L in
  let value, successor = Seed.below ~bound (Seed.make 0x0123456789abcdefL) in
  expect_hex ~label:"one-rejection result" "1573529b34a1d090" value;
  let next, _ = Seed.bits64 successor in
  expect_hex ~label:"one-rejection successor" "2f90b72e996dccbe" next

let bounded_multiple_rejection_consumes_every_word () =
  let bound = 0x4000000000000001L in
  let value, successor = Seed.below ~bound (Seed.make 0x14L) in
  expect_hex ~label:"two-rejection result" "0079d22ed225a1f6" value;
  let next, _ = Seed.bits64 successor in
  expect_hex ~label:"two-rejection successor" "5c83eea29361787c" next

let bounded_rejects_invalid_bounds_before_sampling () =
  let state = Seed.make 0L in
  let expect_invalid ~label bound =
    raises_match ~msg:label
      (Exn.invalid_arg ~exact:"Seed.below: non-positive bound") (fun () ->
        Seed.below ~bound state)
  in
  expect_invalid ~label:"zero bound" 0L;
  expect_invalid ~label:"negative bound" (-1L);
  expect_invalid ~label:"min-int bound" Int64.min_int;
  let first, _ = Seed.bits64 state in
  expect_hex ~label:"invalid bounds leave the input state reusable"
    "e220a8397b1dcdaf" first

(* This oracle computes [2^64 mod bound] and an unsigned word remainder one
   bit at a time. For these small bounds every intermediate is a small signed
   value; it deliberately shares neither [unsigned_rem] nor negation with the
   production sampler. *)
let power_of_two_64_mod bound =
  let rec loop bits remainder =
    if bits = 64 then remainder
    else loop (bits + 1) (Int64.rem (Int64.mul remainder 2L) bound)
  in
  loop 0 1L

let unsigned_word_mod word bound =
  let rec loop bit remainder =
    if bit < 0 then remainder
    else
      let next_bit = Int64.logand (Int64.shift_right_logical word bit) 1L in
      let remainder =
        Int64.rem (Int64.add (Int64.mul remainder 2L) next_bit) bound
      in
      loop (bit - 1) remainder
  in
  loop 63 0L

let rec reference_below_small ~bound ~threshold state =
  let word, state = Seed.bits64 state in
  if Int64.compare word 0L >= 0 && Int64.compare word threshold < 0 then
    reference_below_small ~bound ~threshold state
  else (unsigned_word_mod word bound, state)

let bounded_sampling_agrees_with_independent_small_oracle () =
  let bounds = [ 1L; 2L; 3L; 5L; 10L; 17L; 257L; 65_537L ] in
  let seeds = [ 0L; 1L; 20L; 0x0123456789abcdefL; 0x8000000000000000L; -1L ] in
  List.iter
    (fun bound ->
      let threshold = power_of_two_64_mod bound in
      List.iter
        (fun seed ->
          let initial = Seed.make seed in
          let expected, expected_state =
            reference_below_small ~bound ~threshold initial
          in
          let actual, actual_state = Seed.below ~bound initial in
          let label =
            Printf.sprintf "bound %Ld seed %s" bound (hex_of_int64 seed)
          in
          equal ~msg:label hex64 expected actual;
          let expected_next, _ = Seed.bits64 expected_state in
          let actual_next, _ = Seed.bits64 actual_state in
          equal ~msg:(label ^ " consumption") hex64 expected_next actual_next)
        seeds)
    bounds

let bounded_draws_are_roughly_uniform () =
  let bound = 10L in
  let draws = 10_000 in
  let buckets = Array.make 10 0 in
  let state = ref (Seed.make 42L) in
  for _ = 1 to draws do
    let value, next = Seed.below ~bound !state in
    state := next;
    let index = Int64.to_int value in
    buckets.(index) <- buckets.(index) + 1
  done;
  Array.iteri
    (fun index count ->
      (* Expected 1,000 per bucket, standard deviation ~30; a 200 margin is
         over six sigma, catching gross bias without flakiness. *)
      checkf
        (count > 800 && count < 1200)
        "bucket %d holds %d of %d draws" index count draws)
    buckets

