let derivation_hashes_raw_path_bytes () =
  (* Paths are hashed as raw bytes: NUL, non-ASCII UTF-8, and non-UTF-8 bytes
     all participate. Frozen at v3.0; independently computed in Python. *)
  let vectors =
    [
      ("lone NUL path", 0x0000000000000000L, "\x00", 0, "82b038124ef3e1a9");
      ("embedded NUL path", 0x0000000000000000L, "a\x00b", 0, "ffc9f641efb3864a");
      ( "UTF-8 path",
        0x7be1d2c904aa31f5L,
        "caf\xc3\xa9/na\xc3\xafve \xe2\x9c\x93",
        2,
        "dfaae0f8797a54f4" );
      ( "non-UTF-8 bytes path",
        0x7be1d2c904aa31f5L,
        "\xff\xfe raw \x80 bytes",
        5,
        "04b13d61346b793b" );
    ]
  in
  List.iter
    (fun (label, root, path, index, expected) ->
      expect_hex ~label expected (Seed.derive ~root ~path ~index))
    vectors;
  (* FNV-1a multiplies after every byte, so a trailing NUL still re-keys. *)
  not_equal ~msg:"a trailing NUL byte re-keys the stream" hex64
    (Seed.derive ~root:0L ~path:"a" ~index:0)
    (Seed.derive ~root:0L ~path:"a\x00" ~index:0)

let derivation_is_repeatable_and_sensitive () =
  let base = Seed.derive ~root:0L ~path:"parser/fields" ~index:0 in
  let again = Seed.derive ~root:0L ~path:"parser/fields" ~index:0 in
  equal ~msg:"repeatable derivation" hex64 base again;
  not_equal ~msg:"changing the root changes the case seed" hex64 base
    (Seed.derive ~root:1L ~path:"parser/fields" ~index:0);
  not_equal ~msg:"changing the path changes the case seed" hex64 base
    (Seed.derive ~root:0L ~path:"parser/other" ~index:0);
  not_equal ~msg:"changing the index changes the case seed" hex64 base
    (Seed.derive ~root:0L ~path:"parser/fields" ~index:1)

let derivation_is_distinct_across_paths_and_indices () =
  let module Int64_set = Set.Make (Int64) in
  let paths =
    [
      "a";
      "b";
      "a/b";
      "a/b/c";
      "parser/round trip";
      "parser/round trips";
      "suite/group/leaf name";
      "";
    ]
  in
  let seen = ref Int64_set.empty in
  let count = ref 0 in
  List.iter
    (fun path ->
      for index = 0 to 99 do
        let derived = Seed.derive ~root:0x7be1d2c904aa31f5L ~path ~index in
        checkf
          (not (Int64_set.mem derived !seen))
          "derived seed %s for %S/%d collides" (hex_of_int64 derived) path index;
        seen := Int64_set.add derived !seen;
        incr count
      done)
    paths;
  equal ~msg:"distinctness sweep coverage" int 800 !count

(* Split *)

let split_matches_frozen_literals () =
  let expect_outputs ~label state expected =
    let first, state = Seed.bits64 state in
    let second, _ = Seed.bits64 state in
    expect_hex ~label:(label ^ " word 1") (List.nth expected 0) first;
    expect_hex ~label:(label ^ " word 2") (List.nth expected 1) second
  in
  let fresh, continued = Seed.split (Seed.make 0L) in
  expect_outputs ~label:"fresh of zero" fresh
    [ "184c6c53fb60892d"; "d08944b9dffc3e93" ];
  expect_outputs ~label:"continued of zero" continued
    [ "06c45d188009454f"; "f88bb8a8724c81ec" ];
  let fresh, continued = Seed.split (Seed.make 0x0123456789abcdefL) in
  expect_outputs ~label:"fresh of nontrivial" fresh
    [ "06b8ca9bda6b2d7c"; "428c1e7538260226" ];
  expect_outputs ~label:"continued of nontrivial" continued
    [ "2f90b72e996dccbe"; "a2d419334c4667ec" ]

let split_gamma_regularity_branch_is_frozen () =
  (* [make 0xc3910c8d016b07d6] positions the second internal draw at zero,
     whose derived increment has a regular bit pattern; the mix-gamma
     regularity branch must fire and XOR in 0xaaaaaaaaaaaaaaaa. *)
  let fresh, continued = Seed.split (Seed.make 0xc3910c8d016b07d6L) in
  let first, state = Seed.bits64 fresh in
  let second, _ = Seed.bits64 state in
  expect_hex ~label:"regular-gamma fresh word 1" "f9a602a17425332e" first;
  expect_hex ~label:"regular-gamma fresh word 2" "237d30830cf39d4b" second;
  let first, state = Seed.bits64 continued in
  let second, _ = Seed.bits64 state in
  expect_hex ~label:"regular-gamma continued word 1" "e220a8397b1dcdaf" first;
  expect_hex ~label:"regular-gamma continued word 2" "6e789e6aa1b965f4" second

let split_is_deterministic_and_independent () =
  let state = Seed.make 0xdeadbeefcafebabeL in
  let fresh_a, continued_a = Seed.split state in
  let fresh_b, continued_b = Seed.split state in
  let take n state =
    let rec loop n state values =
      if n = 0 then List.rev values
      else
        let word, state = Seed.bits64 state in
        loop (n - 1) state (word :: values)
    in
    loop n state []
  in
  let words = list hex64 in
  equal ~msg:"splitting the same state twice gives the same fresh stream" words
    (take 4 fresh_a) (take 4 fresh_b);
  equal ~msg:"splitting the same state twice gives the same continued stream"
    words (take 4 continued_a) (take 4 continued_b);
  not_equal ~msg:"fresh and continued streams are distinct" words
    (take 4 fresh_a) (take 4 continued_a);
  not_equal ~msg:"fresh stream is distinct from the parent stream" words
    (take 4 fresh_a) (take 4 state)

let split_fresh_streams_are_distinct_across_seeds () =
  let module Int64_set = Set.Make (Int64) in
  let seen = ref Int64_set.empty in
  for seed = 0 to 99 do
    let fresh, _ = Seed.split (Seed.make (Int64.of_int seed)) in
    let word, _ = Seed.bits64 fresh in
    checkf
      (not (Int64_set.mem word !seen))
      "fresh stream for seed %d collides on its first word" seed;
    seen := Int64_set.add word !seen
  done

(* Entropy *)

let random_produces_distinct_seeds () =
  let rec distinct attempts =
    if attempts = 0 then false
    else if not (Int64.equal (Seed.random ()) (Seed.random ())) then true
    else distinct (attempts - 1)
  in
  is_true ~msg:"six entropy draws produced a single value" (distinct 3)

