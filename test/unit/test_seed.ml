(* Stream and bounded-draw literals were independently computed for
   windtrap-next with arbitrary-precision arithmetic in Python and Ruby and
   are reused unchanged: [Seed.make]/[Seed.bits64] implement the same frozen
   SplitMix64 stream. Derivation, split, and mix-gamma literals were
   independently computed with an arbitrary-precision Python reference of the
   documented definitions. The seed-1234567 vector is the published SplitMix64
   reference vector (Vigna's splitmix64.c, as pinned by rand_xoshiro's test
   suite). None was generated by [Seed]. *)

open Windtrap
module Seed = Windtrap.Private.Seed

let hex_of_int64 value = Printf.sprintf "%016Lx" value

(* Compares with Int64 equality (via the canonical hex image) and renders
   in hex, which is how the frozen literals are written. *)
let hex64 = contramap hex_of_int64 string

let checkf condition format =
  Printf.ksprintf (fun message -> if not condition then fail message) format

let expect_hex ~label expected actual =
  equal ~msg:label string expected (hex_of_int64 actual)

let expect_seed ~label result =
  require_ok ~msg:label ~pp_error:Format.pp_print_string result

let expect_seed_error ~label = function
  | Error _ -> ()
  | Ok seed -> failf "%s: unexpectedly accepted %s" label (hex_of_int64 seed)

(* Token codec *)

let canonical_token_literals () =
  let vectors =
    [
      (0x0000000000000000L, "s1:0000000000000000");
      (0x0000000000000001L, "s1:0000000000000001");
      (0x0123456789abcdefL, "s1:0123456789abcdef");
      (0x7fffffffffffffffL, "s1:7fffffffffffffff");
      (0x8000000000000000L, "s1:8000000000000000");
      (0xffffffffffffffffL, "s1:ffffffffffffffff");
    ]
  in
  List.iter
    (fun (bits, text) ->
      equal ~msg:(text ^ " encode") string text (Seed.to_string bits);
      let decoded =
        expect_seed ~label:(text ^ " decode") (Seed.of_string text)
      in
      equal ~msg:(text ^ " bits") hex64 bits decoded)
    vectors

let all_token_patterns_round_trip () =
  (* A 64-bit LCG walk gives 1,024 well-spread bit patterns. *)
  let rec loop remaining bits =
    if remaining = 0 then ()
    else begin
      let text = Seed.to_string bits in
      let decoded =
        expect_seed ~label:("round trip " ^ text) (Seed.of_string text)
      in
      equal ~msg:("round trip " ^ text) hex64 bits decoded;
      let bits =
        Int64.add (Int64.mul bits 0x5851f42d4c957f2dL) 0x14057b7ef767814fL
      in
      loop (remaining - 1) bits
    end
  in
  loop 1_024 0x6a09e667f3bcc909L

let token_parser_rejects_malformed_text () =
  let rejected =
    [
      "";
      "s1:";
      "s1:000000000000000";
      "s1:00000000000000000";
      "s1:000000000000000A";
      "s1:000000000000000g";
      "s1:0000000000000000\x00";
      "s1:0000000000000000 ";
      " s1:0000000000000000";
      "S1:0000000000000000";
      "s01:0000000000000000";
      "s2:0000000000000000";
      "0000000000000000";
      "0x0000000000000000";
      "42";
      "+1";
      "-1";
    ]
  in
  List.iter
    (fun text ->
      expect_seed_error ~label:(String.escaped text) (Seed.of_string text))
    rejected

